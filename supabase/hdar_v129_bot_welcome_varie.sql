create or replace function hdar.bot_questions() returns int
language plpgsql security definer set search_path to '' as $$
declare cfg hdar.bot_settings; r record; n int := 0; h int := extract(hour from now() at time zone 'Europe/Paris');
  d date := (now() at time zone 'Europe/Paris')::date; nq int; qi int; lg text;
begin
  select * into cfg from hdar.bot_settings where id;
  if cfg is null or not cfg.question_on or h < 10 or h >= 22 then return 0; end if;
  select count(*) into nq from hdar.bot_text where kind = 'q' and lang = 'fr';
  if nq = 0 then return 0; end if;
  for r in select s.id from hdar.salons s
    where not s.removed
      and (s.official or exists (select 1 from hdar.salon_messages m where m.salon_id = s.id and m.from_id <> hdar.bot_id() and m.created_at > now() - interval '7 days'))
      and not exists (select 1 from hdar.salon_messages m where m.salon_id = s.id and not m.removed and m.created_at > now() - interval '3 hours')
      and not exists (select 1 from hdar.bot_salon_log l where l.salon_id = s.id and l.kind = 'question' and l.day = d)
    limit 30 loop
    lg := hdar.salon_lang(r.id);
    select i into qi from generate_series(1, nq) i
      left join lateral (select max(q.at) last from hdar.bot_question_log q where q.salon_id = r.id and q.idx = i) u on true
      order by u.last nulls first, random() limit 1;
    perform hdar.bot_salon_post(r.id, replace(hdar.bot_txt('qprefix', 1, lg), '{q}', hdar.bot_txt('q', qi, lg)), 'question');
    insert into hdar.bot_question_log (salon_id, idx) values (r.id, qi);
    n := n + 1;
  end loop;
  return n;
end $$;
revoke all on function hdar.bot_questions() from public, anon, authenticated;

-- Rappel des règles : texte par défaut → version sans emoji, dans la langue du salon. Texte personnalisé : inchangé.
create or replace function hdar.bot_salon_post(p_salon uuid, p_body text, p_kind text) returns void
language plpgsql security definer set search_path to '' as $$
declare b text := p_body;
begin
  if p_kind = 'rules' and b like 'Petit rappel amical %' then b := coalesce(hdar.bot_txt('rules', 1, hdar.salon_lang(p_salon)), b); end if;
  insert into hdar.salon_messages (salon_id, from_id, pseudo, body) values (p_salon, hdar.bot_id(), 'hdar', left(b, 1000));
  update hdar.salons set last_at = now() where id = p_salon;
  insert into hdar.bot_salon_log (salon_id, kind, day) values (p_salon, p_kind, (now() at time zone 'Europe/Paris')::date);
end $$;
revoke all on function hdar.bot_salon_post(uuid, text, text) from public, anon, authenticated;

language sql stable security definer set search_path to '' as $$
  select hdar.bot_lang(coalesce(s.country, s.scope_cc)) from hdar.salons s where s.id = p_salon $$;

create or replace function hdar.bot_txt(p_kind text, p_idx int, p_lang text) returns text
language sql stable security definer set search_path to '' as $$
  select t.txt from hdar.bot_text t where t.kind = p_kind and t.idx = p_idx and t.lang in (p_lang, 'en', 'fr')
  order by (t.lang = p_lang) desc, (t.lang = 'en') desc limit 1 $$;

create or replace function hdar.bot_welcome_pick(p_one boolean, p_lang text default 'fr') returns text
language sql volatile security definer set search_path to '' as $$
  select hdar.bot_txt(k, 1 + floor(random() * (select count(*) from hdar.bot_text t where t.kind = k and t.lang = 'fr'))::int, p_lang)
  from (select case when p_one then 'one' else 'many' end k) x $$;

-- « @a, @b et @c » avec le « et » de la langue.
create or replace function hdar.bot_join_mentions(p_names text[], p_lang text) returns text
language sql immutable set search_path to '' as $$
  select case when coalesce(array_length(p_names, 1), 0) <= 1 then hdar.mention_tag(p_names[1])
    else array_to_string((select array_agg(hdar.mention_tag(x)) from unnest(p_names[1:array_length(p_names, 1) - 1]) x), ', ')
      || ' ' || case p_lang when 'fr' then 'et' when 'es' then 'y' when 'de' then 'und' when 'it' then 'e' when 'pt' then 'e'
                 when 'ar' then 'و' when 'nl' then 'en' when 'pl' then 'i' when 'tr' then 've' when 'ru' then 'и' else 'and' end
      || ' ' || hdar.mention_tag(p_names[array_length(p_names, 1)]) end $$;


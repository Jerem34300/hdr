-- Mention : crochets dès que le pseudo n'est pas un mot ASCII (accents, espaces…), pour un rendu entier côté client.
create or replace function hdar.mention_tag(p text) returns text
language sql immutable set search_path to '' as $$
  select case when btrim(p) ~ '^[A-Za-z0-9_.\-]+$' then '@' || btrim(p) else '@[' || btrim(p) || ']' end
$$;

create or replace function hdar.geo_key(p_lat double precision, p_lng double precision) returns text
language sql immutable set search_path to '' as $$ select round(p_lat::numeric, 1) || ',' || round(p_lng::numeric, 1) $$;

create or replace function hdar.geo_city_label(p_lat double precision, p_lng double precision) returns text
language sql stable security definer set search_path to '' as $$
  select g.label from hdar.geo_city g where p_lat is not null and p_lng is not null and g.k = hdar.geo_key(p_lat, p_lng) $$;

-- Langue d'un pays (ISO 3166 alpha-2) ; sans pays → français ; langue sans textes → anglais.
create or replace function hdar.bot_lang(p_cc text) returns text
language sql stable security definer set search_path to '' as $$
  select case when x.l is not null and exists (select 1 from hdar.bot_text t where t.kind = 'one' and t.lang = x.l) then x.l else 'en' end
  from (select case when nullif(btrim(coalesce(p_cc, '')), '') is null then 'fr'
                    else (select c.lang from hdar.country_lang c where c.cc = upper(btrim(p_cc))) end l) x $$;


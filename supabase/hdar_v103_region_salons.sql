    'recent', (select count(*) from hdar.salon_messages m where m.salon_id = x.id and not m.removed and m.created_at > now() - interval '24 hours'),
    'people', (select count(distinct m.from_id) from hdar.salon_messages m where m.salon_id = x.id and not m.removed and m.created_at > now() - interval '24 hours'))
  from hdar.salons x where x.id = p_id;
$$;
revoke execute on function hdar.salon_row(uuid, text) from public, anon, authenticated;

-- Régions d'un pays : salons existants + subdivisions pas encore ouvertes (id null). Liste courte : un seul pays.
create or replace function public.hdar_regions(p_cc text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare s text := hdar.self_id(); v_cc text := upper(btrim(coalesce(p_cc, '')));
begin
  if s is null then raise exception 'Session requise'; end if;
  return coalesce((select jsonb_agg(r order by (r->>'recent')::int desc, r->>'name') from (
    select hdar.salon_row(x.id, s) || jsonb_build_object('code', x.region) r
      from hdar.salons x where not x.removed and x.region is not null and x.scope_cc = v_cc
    union all
    select jsonb_build_object('id', null, 'code', d.code, 'name', d.name, 'recent', 0, 'cc', v_cc)
      from hdar.subdivisions d where d.cc = v_cc
       and not exists (select 1 from hdar.salons x where not x.removed and x.scope_cc = v_cc and x.region = d.code)) t), '[]'::jsonb);
end $$;

-- Salon d'une région (créé au premier passage, rattaché au pays).
create or replace function public.hdar_region_salon(p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare s text := hdar.self_id(); c text := upper(btrim(coalesce(p_code, ''))); d hdar.subdivisions; v uuid;
begin
  if s is null then raise exception 'Session requise'; end if;
  select * into d from hdar.subdivisions where code = c;
  if d.code is null then raise exception 'Région inconnue'; end if;
  select id into v from hdar.salons where scope_cc = d.cc and region = d.code and not removed;
  if v is null then
    perform hdar.rate_check(s, 'region_salon', 20, interval '1 hour');
    insert into hdar.salons (name, description, official, region, scope_cc)
    values (d.name, 'Salon de la région · ' || d.name, true, d.code, d.cc)
    on conflict do nothing returning id into v;
    if v is null then select id into v from hdar.salons where scope_cc = d.cc and region = d.code and not removed; end if;
  end if;
  return hdar.salon_row(v, s);
end $$;

-- Création d'un salon thématique rattaché au pays choisi.
create or replace function public.hdar_salon_create_cc(p_name text, p_description text, p_emoji text, p_cc text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare s text := hdar.self_id(); cc text := upper(btrim(coalesce(p_cc, ''))); v uuid;
begin
  if not exists (select 1 from hdar.countries where code = cc) then raise exception 'Pays inconnu'; end if;
  v := public.hdar_salon_create(p_name, p_description, p_emoji);
  update hdar.salons set scope_cc = cc where id = v and creator_id = s;
  return v;
end $$;

-- Liste : sans les régions des autres pays (elles passent par hdar_regions).
create or replace function public.hdar_salons() returns jsonb
 language plpgsql stable security definer set search_path to '' as $function$
declare s text := hdar.self_id();
begin
  if s is null then raise exception 'Session requise'; end if;
  return coalesce((select jsonb_agg(hdar.salon_row(x.id, s) order by x.official desc, x.last_at desc)
    from (select * from hdar.salons where not removed and trip_key is null and (region is null or scope_cc = 'FR')
          order by official desc, last_at desc limit 100) x), '[]'::jsonb);
end $function$;

-- 3) Trajets : clé = mode | [réseau |] numéro | date, normalisée (majuscules, sans espaces ni ponctuation).
create or replace function hdar.trip_norm(p text) returns text language sql immutable set search_path = '' as $$
  select left(regexp_replace(upper(coalesce(p, '')), '[^[:alnum:]]', '', 'g'), 40);
$$;

-- Train : la clé garde le numéro seul (v99) ; métro/bus : ligne et réseau normalisés ; vol : déjà sans espaces.
create or replace function public.hdar_trip_join(p_kind text, p_code text, p_day date, p_place uuid, p_network text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare s text := hdar.self_id(); c text := hdar.trip_code(p_kind, p_code); d date := coalesce(p_day, current_date);
  net text := left(regexp_replace(btrim(coalesce(p_network, '')), '\s+', ' ', 'g'), 40);
  k text; nm text; v uuid; num text;
begin
  if s is null then raise exception 'Session requise'; end if;
  perform hdar.require_profile(s);
  if exists (select 1 from hdar.bans b where b.user_id = s and b.active) then raise exception 'Compte suspendu'; end if;
  if p_kind = 'train' then
    if c !~ '^([A-Z][A-Z ]{0,23} ?)?[0-9]{1,6}[A-Z]?$' then raise exception 'Numéro de train invalide (ex. TGV 6201)'; end if;
    num := substring(c from '([0-9]{1,6})[A-Z]?$');
    nm := c;
  elsif p_kind = 'flight' then
    if c !~ '^[A-Z0-9]{2}[A-Z]?[0-9]{1,4}[A-Z]?$' then raise exception 'Numéro de vol invalide (ex. AF1234)'; end if;
    num := hdar.trip_norm(c); nm := 'Vol ' || c;
  elsif p_kind in ('metro', 'bus') then
    if length(c) < 1 then raise exception 'Choisis ta ligne'; end if;
    num := hdar.trip_norm(c);
    if num = '' then raise exception 'Choisis ta ligne'; end if;
    nm := btrim(left(initcap(lower(c)) || case when net <> '' then ' · ' || net else '' end, 60));
  else raise exception 'Type de trajet inconnu'; end if;
  if d not between current_date - 1 and current_date + 1 then raise exception 'Date : hier, aujourd''hui ou demain'; end if;
  k := p_kind || '|' || case when p_kind in ('metro', 'bus') then hdar.trip_norm(net) || '|' else '' end || num || '|' || d::text;
  perform hdar.rate_check(s, 'trip_join', 20, interval '1 hour');
  select x.id into v from hdar.salons x where x.trip_key = k and not x.removed;
  if v is null then
    insert into hdar.salons (name, description, trip_kind, trip_key, expires_at, creator_id)
    values (nm, to_char(d, 'DD/MM'), p_kind, k, least(((d + 1)::timestamp + interval '6 hours') at time zone 'UTC', now() + interval '36 hours'), null)
    on conflict do nothing returning salons.id into v;
    if v is null then select x.id into v from hdar.salons x where x.trip_key = k and not x.removed; end if;
  end if;
  insert into hdar.trip_members (salon_id, user_id) values (v, s)
    on conflict (salon_id, user_id) do update set joined_at = now();
  if p_place is not null and exists (select 1 from hdar.places p where p.id = p_place and p.kind in ('station','metro','airport')) then
    insert into hdar.trip_stops (salon_id, place_id) values (v, p_place) on conflict do nothing;
  end if;
  return hdar.trip_row(v, s);
end $$;

-- Boîte de réception : sans les régions des autres pays, sauf celles où j'ai écrit.
create or replace function public.hdar_salons_inbox(p_seen jsonb)
 returns jsonb language plpgsql stable security definer set search_path to '' as $function$
declare s text := hdar.self_id(); seen jsonb := coalesce(p_seen, '{}'::jsonb);
begin
  if s is null then raise exception 'Session requise'; end if;
  if jsonb_typeof(seen) <> 'object' then seen := '{}'::jsonb; end if;
  return coalesce((select jsonb_agg(hdar.salon_row(x.id, s) || jsonb_build_object(
      'wrote', exists (select 1 from hdar.salon_messages m where m.salon_id = x.id and m.from_id = s and not m.removed
                       and m.created_at > now() - interval '24 hours'),
      'unread', case when seen ? x.id::text then (select count(*) from hdar.salon_messages m
                  where m.salon_id = x.id and not m.removed and m.from_id <> s
                    and m.created_at > hdar.safe_ts(seen ->> x.id::text) and not hdar.is_blocked(s, m.from_id)) else 0 end,
      'replies', case when seen ? x.id::text then (select count(*) from hdar.salon_messages m
                  join hdar.salon_messages o on o.id = m.reply_to and o.from_id = s
                  where m.salon_id = x.id and not m.removed and m.from_id <> s
                    and m.created_at > hdar.safe_ts(seen ->> x.id::text) and not hdar.is_blocked(s, m.from_id)) else 0 end,
      'last', (select jsonb_build_object('pseudo', m.pseudo, 'at', m.created_at, 'mine', m.from_id = s,
                 'body', hdar.reply_preview(m.pseudo, m.body, m.kind, false) ->> 'body')
               from hdar.salon_messages m where m.salon_id = x.id and not m.removed and not hdar.is_blocked(s, m.from_id)
                 and m.created_at > now() - interval '24 hours'
               order by m.created_at desc limit 1))
      order by x.official desc, x.last_at desc)
    from (select * from hdar.salons y where not y.removed
            and (y.region is null or y.scope_cc = 'FR' or exists (select 1 from hdar.salon_messages m where m.salon_id = y.id and m.from_id = s and m.created_at > now() - interval '24 hours'))
            and (y.trip_key is null or (y.expires_at > now() and exists (select 1 from hdar.trip_members t
                   where t.salon_id = y.id and t.user_id = s and t.joined_at > now() - interval '12 hours')))
          order by official desc, last_at desc limit 100) x), '[]'::jsonb);
end $function$;

